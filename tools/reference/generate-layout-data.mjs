// Development-only extraction from the verified KaTeX 0.19.0 source and font data.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import ts from 'typescript';
import {root, sourceRoot, sha256} from './acquire.mjs';

const manifest=JSON.parse(fs.readFileSync(path.join(root,'docs/reference/katex-0.19.0.files.json'),'utf8'));
function source(relative) {
  const bytes=fs.readFileSync(path.join(sourceRoot,relative));
  if(sha256(bytes)!==manifest.sourceFiles.find(x=>x.path===relative)?.sha256)throw new Error(`Source hash mismatch: ${relative}`);
  return bytes.toString('utf8');
}
const format=n=>Number.isInteger(n)?`${n}d`:`${Number(n.toPrecision(14))}d`;
function output(relative,text) {
  const file=path.join(root,relative),bytes=text+'\n';
  if(process.argv.includes('--check')) {if(fs.readFileSync(file,'utf8')!==bytes)throw new Error(`Generated output differs: ${relative}`);}
  else fs.writeFileSync(file,bytes);
}

// Reading an explicitly named AST literal avoids executing the metrics module.
const metricsSource=source('src/fontMetrics.ts');
const ast=ts.createSourceFile('fontMetrics.ts',metricsSource,ts.ScriptTarget.Latest,true);
let metricNode;
function visit(node) {if(ts.isVariableDeclaration(node)&&node.name.getText(ast)==='sigmasAndXis')metricNode=node.initializer;ts.forEachChild(node,visit);}
visit(ast);
if(!metricNode||!ts.isObjectLiteralExpression(metricNode))throw new Error('Missing static metrics literal');
const metrics=[];
for(const p of metricNode.properties) {
  if(!ts.isPropertyAssignment(p)||!ts.isArrayLiteralExpression(p.initializer))throw new Error('Unexpected metrics syntax');
  const values=p.initializer.elements.map(x=>{if(!ts.isNumericLiteral(x))throw new Error('Nonliteral metric');return Number(x.text);});
  if(values.length!==3)throw new Error('Unexpected metrics columns');
  metrics.push([p.name.getText(ast),values]);
}
output('src/VelociTex.Core/Generated/MathConstants.g.cs',[
  '// <auto-generated />', '// KaTeX 0.19.0 fontMetrics.ts; generated by tools/reference/generate-layout-data.mjs.',
  `// Source SHA-256: ${sha256(Buffer.from(metricsSource))}`, 'namespace VelociTex;', '',
  'internal static class MathConstants','{',
  ...metrics.map(([name,v])=>`    internal static double ${name}(int index) => index switch { 0 => ${format(v[0])}, 1 => ${format(v[1])}, _ => ${format(v[2])} };`),
  '}',
].join('\n'));

const dataPath=path.join(root,'src/VelociTex.Core/Generated/font-data.json');
const data=JSON.parse(fs.readFileSync(dataPath,'utf8'));
for(const font of data.fonts) {
  const bytes=fs.readFileSync(path.join(root,'src/VelociTex.Core/Resources/Fonts',font.file));
  if(sha256(bytes)!==manifest.packageFiles.find(x=>x.path==='dist/fonts/'+font.file)?.sha256)throw new Error(`Font hash mismatch: ${font.file}`);
}
output('src/VelociTex.Core/Generated/GlyphInkData.g.cs',[
  '// <auto-generated />','// Exact glyf bounds matching FontData.Glyphs indices; generated by tools/reference/generate-layout-data.mjs.',
  `// font-data.json SHA-256: ${sha256(fs.readFileSync(dataPath))}`,'namespace VelociTex;','',
  'internal readonly record struct GlyphInk(short Left,short Bottom,short Right,short Top);',
  'internal static class GlyphInkData','{','    internal static readonly GlyphInk[] Bounds =','    [',
  ...data.fonts.flatMap(font=>[`        // ${font.name}`,...font.cmap.map(m=>`        new(${font.glyphs[m.glyphId].inkBoundsUnits.join(', ')}),`)]),
  '    ];','}',
].join('\n'));

// The locked geometry module has no imports. Execute its actual exported path
// function at build time, then normalize to compact absolute drawing segments.
const geometrySource=source('src/svgGeometry.ts');
const js=ts.transpileModule(geometrySource,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const context={exports:{}};vm.runInNewContext(js,context,{timeout:3000});
function normalize(d) {
  const t=d.match(/[a-zA-Z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?/g);
  let i=0,x=0,y=0,sx=0,sy=0,cx=0,cy=0,previous='';const result=[];
  while(i<t.length) {
    const command=t[i++],upper=command.toUpperCase(),relative=command!==upper;
    if(!/^[MLHVCSZ]$/i.test(command))throw new Error(`Unsupported geometry command: ${command}`);
    if(upper==='Z'){result.push(['Close',0,0]);x=sx;y=sy;previous='Z';continue;}
    let first=true;
    while(i<t.length&&!/^[a-zA-Z]$/.test(t[i])) {
      const count={M:2,L:2,H:1,V:1,C:6,S:4}[upper];
      const v=t.slice(i,i+count).map(Number);i+=count;
      const px=x,py=y;
      const ax=n=>n+(relative?px:0),ay=n=>n+(relative?py:0);
      if(upper==='M'||upper==='L'){x=ax(v[0]);y=ay(v[1]);result.push([upper==='M'&&first?'Move':'Line',x,y]);if(upper==='M'&&first){sx=x;sy=y;}}
      else if(upper==='H'){x=ax(v[0]);result.push(['Line',x,y]);}
      else if(upper==='V'){y=ay(v[0]);result.push(['Line',x,y]);}
      else if(upper==='C'){cx=ax(v[2]);cy=ay(v[3]);x=ax(v[4]);y=ay(v[5]);result.push(['Cubic',ax(v[0]),ay(v[1]),cx,cy,x,y]);}
      else if(upper==='S'){const c1x=previous==='C'||previous==='S'?2*px-cx:px,c1y=previous==='C'||previous==='S'?2*py-cy:py;cx=ax(v[0]);cy=ay(v[1]);x=ax(v[2]);y=ay(v[3]);result.push(['Cubic',c1x,c1y,cx,cy,x,y]);}
      previous=upper;first=false;
    }
  }
  return result;
}
const names=['sqrtMain','sqrtSize1','sqrtSize2','sqrtSize3','sqrtSize4','sqrtTall'];
const paths=names.map(n=>normalize(context.exports.sqrtPath(n,0,4000)));
const tallNext=normalize(context.exports.sqrtPath('sqrtTall',0,4001));
const tallDelta=paths[5].map((s,i)=>s.map((v,j)=>j===0?v:tallNext[i][j]-v));
output('src/VelociTex.Core/Generated/RadicalPathData.g.cs',[
  '// <auto-generated />','// Canonical absolute segments from locked KaTeX 0.19.0 sqrtPath; no SVG parser runs in the product.',
  '// Regenerate: node tools/reference/generate-layout-data.mjs',
  `// svgGeometry.ts SHA-256: ${sha256(Buffer.from(geometrySource))}`,'namespace VelociTex;','',
  'internal static class RadicalPathData','{',
  ...paths.flatMap((segments,i)=>[`    internal static readonly MathPathSegment[] ${names[i]} =`,`    [`,...segments.map(s=>`        new(MathPathOperation.${s[0]}, ${s.slice(1).map(format).join(', ')}),`),'    ];']),
  '    internal static MathPathSegment[] Tall(double viewBoxHeight)','    {',
  '        double d = viewBoxHeight - 4000d;','        return','        [',
  ...paths[5].map((s,i)=>`            new(MathPathOperation.${s[0]}, ${s.slice(1).map((v,j)=>Math.abs(tallDelta[i][j+1])>1e-10?`${format(v)} + ${format(tallDelta[i][j+1])} * d`:format(v)).join(', ')}),`),
  '        ];','    }','}',
].join('\n'));
console.log(JSON.stringify({fonts:data.fonts.length,glyphBounds:data.fonts.reduce((n,f)=>n+f.cmap.length,0),metrics:metrics.length,radicalPaths:paths.length,normalizedSegments:paths.reduce((n,p)=>n+p.length,0),check:process.argv.includes('--check')}));
