import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import {createRequire} from 'node:module';
import {root,sha256} from './acquire.mjs';
const source=path.join(root,'artifacts/upstream/source/src');
const locked=JSON.parse(await fs.readFile(path.join(root,'tools/reference/data/katex-0.19.0.files.json'),'utf8'));
const files=['unicodeAccents.js','unicodeSymbols.js','unicodeSupOrSub.ts'];
for(const file of files){
 const target='src/'+file;
 const entry=locked.sourceFiles.find(x=>x.path===target);
 if(!entry||sha256(await fs.readFile(path.join(source,file)))!==entry.sha256)throw new Error('Locked Unicode source drift: '+target);
}
const require=createRequire(import.meta.url);
const accents=require(path.join(source,'unicodeAccents.js'));
const decomposed=require(path.join(source,'unicodeSymbols.js'));
const superSource=await fs.readFile(path.join(source,'unicodeSupOrSub.ts'),'utf8');
const mapText=superSource.slice(superSource.indexOf('Object.freeze(')+'Object.freeze('.length).trim().replace(/\);\s*$/,'');
const scripts=vm.runInNewContext('('+mapText+')',Object.create(null));
const subChars='₊₋₌₍₎₀₁₂₃₄₅₆₇₈₉ₐₑₕᵢⱼₖₗₘₙₒₚᵣₛₜᵤᵥₓᵦᵧᵨᵩᵪ';
const quote=s=>JSON.stringify(s);
const text='// <auto-generated />\n#nullable enable\n// Exact KaTeX 0.19.0 Unicode parser maps; generate-unicode-data.mjs.\nnamespace VelociTex;\ninternal static class UnicodeData\n{\n'+
'    internal static string? Decompose(int scalar) => scalar switch\n    {\n'+Object.entries(decomposed).sort((a,b)=>a[0].codePointAt(0)-b[0].codePointAt(0)).map(([k,v])=>'        '+k.codePointAt(0)+' => '+quote(v)+',').join('\n')+'\n        _ => null,\n    };\n'+
'    internal static string? Accent(int scalar, bool text) => scalar switch\n    {\n'+Object.entries(accents).map(([k,v])=>'        '+k.codePointAt(0)+' => '+(v.math?'text ? '+quote(v.text)+' : '+quote(v.math):quote(v.text))+',').join('\n')+'\n        _ => null,\n    };\n'+
'    internal static string? Script(int scalar, out bool subscript)\n    {\n        subscript = scalar is '+[...subChars].map(c=>c.codePointAt(0)).join(' or ')+';\n        return scalar switch\n        {\n'+Object.entries(scripts).sort((a,b)=>a[0].codePointAt(0)-b[0].codePointAt(0)).map(([k,v])=>'            '+k.codePointAt(0)+' => '+quote(v)+',').join('\n')+'\n            _ => null,\n        };\n    }\n}\n';
const destination=path.join(root,'src/VelociTex.Core/Generated/UnicodeData.g.cs');
if(process.argv.includes('--check')) {if((await fs.readFile(destination,'utf8')).replaceAll('\r\n','\n')!==text)throw new Error('Unicode generated data drift');}
else await fs.writeFile(destination,text);
console.log(`Exact Unicode maps: ${Object.keys(decomposed).length} decompositions, ${Object.keys(accents).length} accents, ${Object.keys(scripts).length} scripts.`);
