import fs from 'node:fs/promises';
import path from 'node:path';
import {root, sha256} from './acquire.mjs';
import {loadSource} from './load-source.mjs';

const loaded=loadSource();
const atom={mathord:'Ord',textord:'Ord',bin:'Bin',rel:'Rel',open:'Open',close:'Close',punct:'Punct',inner:'Inner','op-token':'Op',spacing:'Ord','accent-token':'Ord'};
const quote=x=>JSON.stringify(x).replaceAll('\\u2028','\\u2028').replaceAll('\\u2029','\\u2029');
const rows=[];
for(const [mode,values] of Object.entries(loaded.symbols)) for(const [name,data] of Object.entries(values)) {
  const replacement=data.replace??name;
  const cps=[...replacement];
  rows.push({name,mode,data,cp:cps.length===1?replacement.codePointAt(0):-1});
}
rows.sort((a,b)=>(a.mode==='text')-(b.mode==='text')||(a.name<b.name?-1:a.name>b.name?1:0));
let output='// <auto-generated />\n// Locked KaTeX 0.19.0; tools/reference/generate-core-symbols.mjs.\nnamespace VelociTex;\n\ninternal readonly record struct SymbolDefinition(string Name, int CodePoint, MathAtom Atom, MathFont Font, bool IsMathOrd, bool TextMode, string Group);\ninternal static class SymbolData\n{\n    internal static readonly SymbolDefinition[] Symbols =\n    [\n';
for(const {name,mode,data,cp} of rows) output+=`        new(${quote(name)}, ${cp}, MathAtom.${atom[data.group]??'Ord'}, MathFont.${data.font==='ams'?'AMS':'Default'}, ${data.group==='mathord'?'true':'false'}, ${mode==='text'?'true':'false'}, ${quote(data.group)}),\n`;
output+='    ];\n    internal static readonly (string Name, string Body)[] Macros =\n    [\n';
for(const [name,body] of Object.entries(loaded.macros).filter(([,body])=>typeof body==='string').sort(([a],[b])=>a<b?-1:a>b?1:0)) output+=`        (${quote(name)}, ${quote(body)}),\n`;
output+='    ];\n    internal static readonly string[] KnownCommands =\n    [\n';
for(const name of [...new Set([...Object.keys(loaded.functions._functions),...Object.keys(loaded.macros),...rows.map(x=>x.name)])].sort()) output+=`        ${quote(name)},\n`;
output+='    ];\n}\n';
const target=path.join(root,'src/VelociTex.Core/Generated/SymbolData.g.cs');
if(process.argv.includes('--check')) {if(await fs.readFile(target,'utf8')!==output)throw Error('Generated symbol data drift');}
else await fs.writeFile(target,output);
console.log(JSON.stringify({symbols:rows.length,stringMacros:Object.values(loaded.macros).filter(x=>typeof x==='string').length,sha256:sha256(Buffer.from(output))}));
