import fs from 'node:fs/promises';
import path from 'node:path';
import { root, sourceRoot, sha256 } from './acquire.mjs';
import { loadSource } from './load-source.mjs';
const manifest = JSON.parse(await fs.readFile(path.join(root, 'tools/reference/data/katex-0.19.0.files.json'), 'utf8'));
const upstream = loadSource();
for (const module of upstream.moduleSources) {
  const entry = manifest.sourceFiles.find((x) => x.path === module);
  if (!entry || sha256(await fs.readFile(path.join(sourceRoot, module))) !== entry.sha256)
    throw new Error('Locked command source drift: ' + module);
}
const functions = upstream.functions._functions;
const entries = Object.entries(functions).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
const source =
  '// <auto-generated />\n// Exact locked KaTeX 0.19.0 function argument and mode rules.\nnamespace VelociTex;\ninternal readonly record struct CommandDefinition(string Name, bool AllowedInText, bool AllowedInMath, bool AllowedInArgument, bool Primitive);\ninternal static class CommandData\n{\n    internal static readonly CommandDefinition[] Definitions =\n    [\n' +
  entries
    .map(
      ([name, entry]) =>
        '        new(' +
        JSON.stringify(name) +
        ', ' +
        !!entry.allowedInText +
        ', ' +
        (entry.allowedInMath !== false) +
        ', ' +
        !!entry.allowedInArgument +
        ', ' +
        !!entry.primitive +
        '),'
    )
    .join('\n') +
  '\n    ];\n}\n';
const target = path.join(root, 'src/VelociTex.Core/Generated/CommandData.g.cs');
if (process.argv.includes('--check')) {
  if ((await fs.readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== source) throw new Error('Command data drift');
} else await fs.writeFile(target, source);
console.log('Locked command mode/argument rules: ' + entries.length);
