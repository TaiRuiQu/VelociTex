"""Compose the rendering comparison poster with matplotlib.

Inputs (generated by the benchmark tooling):
  artifacts/comparison/<id>-native.png  — Windows Direct2D export, transparent, 2x
  artifacts/comparison/<id>-wasm.png    — WASM binding in Chrome, screenshot, 2x
  artifacts/comparison/<id>-katex.png   — KaTeX 0.19.0 in Chrome, screenshot, 2x

The output uses a pure white background, explicit card borders, equal white
padding and neutral typography so the formulas — not the decoration — carry the
comparison.
"""

import argparse
import json
import pathlib
import textwrap

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib import font_manager
from PIL import Image

plt.rcParams.update(
    {
        "font.sans-serif": ["Microsoft YaHei", "Segoe UI", "DejaVu Sans"],
        "font.family": "sans-serif",
        "axes.unicode_minus": False,
        "figure.facecolor": "white",
        "axes.facecolor": "white",
        "savefig.facecolor": "white",
        "text.color": "#111820",
    }
)

INK = "#0b1f33"
MUTED = "#5d6b78"
BORDER = "#c6d0da"
ACCENT = "#1f4e79"


def white_image(path):
    image = Image.open(path).convert("RGBA")
    canvas = Image.new("RGBA", image.size, (255, 255, 255, 255))
    canvas.alpha_composite(image)
    return canvas.convert("RGB")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default="artifacts/comparison")
    parser.add_argument("--out", default="docs/benchmarks/comparison-overview.png")
    parser.add_argument("--formulas", default="benchmarks/comparison.json")
    args = parser.parse_args()
    data = pathlib.Path(args.data)
    formulas = json.loads(pathlib.Path(args.formulas).read_text(encoding="utf-8"))
    output = pathlib.Path(args.out)
    output.parent.mkdir(parents=True, exist_ok=True)

    engines = [
        ("native", "Windows 原生", "DirectWrite / Direct2D"),
        ("wasm", "WebAssembly Binding", "C++ MathML + 浏览器排版"),
        ("katex", "KaTeX 0.19.0", "HTML + SVG"),
    ]

    columns = 1 + len(engines)
    fig = plt.figure(figsize=(16.4, 12.6))
    grid = fig.add_gridspec(
        len(formulas) + 1,
        columns,
        height_ratios=[0.36] + [1] * len(formulas),
        width_ratios=[1.06, 1.75, 1.75, 1.75],
        left=0.035,
        right=0.975,
        top=0.885,
        bottom=0.075,
        wspace=0.07,
        hspace=0.13,
    )

    fig.text(0.035, 0.962, "VELOCITEX · RENDERING COMPARISON", fontsize=9.5, fontweight="bold", color=ACCENT)
    fig.text(0.035, 0.925, "同一公式，三种真实渲染", fontsize=24, fontweight="bold", color=INK)
    fig.text(
        0.035,
        0.899,
        "Windows 原生 Direct2D · VelociTex WASM binding · KaTeX 0.19.0　｜　32 px 数学字号，纯白背景，实际光栅输出",
        fontsize=9.8,
        color=MUTED,
    )

    for column, (_, name, detail) in enumerate(engines, start=1):
        header = fig.add_subplot(grid[0, column])
        header.set_axis_off()
        header.text(0.5, 0.62, name, ha="center", va="center", fontsize=11.5, fontweight="bold", color=INK)
        header.text(0.5, 0.18, detail, ha="center", va="center", fontsize=8.2, color=MUTED)

    for row, formula in enumerate(formulas, start=1):
        label = fig.add_subplot(grid[row, 0])
        label.set_axis_off()
        label.text(0.0, 0.80, formula["title"], ha="left", va="top", fontsize=11.5, fontweight="bold", color=INK)
        label.text(
            0.0,
            0.55,
            "\n".join(textwrap.wrap(formula["latex"], width=38)),
            ha="left",
            va="top",
            fontfamily="Consolas",
            fontsize=6.9,
            color=MUTED,
            linespacing=1.45,
        )

        for column, (engine, _, _) in enumerate(engines, start=1):
            path = data / f"{formula['id']}-{engine}.png"
            axis = fig.add_subplot(grid[row, column])
            image = white_image(path)
            axis.imshow(image, interpolation="lanczos")
            axis.set_xticks([])
            axis.set_yticks([])
            axis.set_facecolor("white")
            for spine in axis.spines.values():
                spine.set_visible(True)
                spine.set_color(BORDER)
                spine.set_linewidth(1.05)
            axis.set_anchor("C")

    fig.text(
        0.035,
        0.035,
        "渲染尺寸统一为 32 px 数学 em（图像按 2× 采样）；原生列为 DirectWrite/Direct2D 导出的透明 PNG，白底合成；浏览器列由无头 Chrome 截取。\n"
        "允许抗锯齿与亚像素差异；本图展示代表性公式，不构成所有输入或所有浏览器的像素一致性承诺。",
        fontsize=7.9,
        color=MUTED,
        linespacing=1.6,
    )

    fig.savefig(output, dpi=200, facecolor="white", edgecolor="none")
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
